/* 英文單字庫（基礎 960）
   做法：打開你原本程式碼，找到 const VOCAB_DATABASE = [ … ];
   把中括號 [ ] 裡面的所有 { id: 1, word: "person", … }, 整段複製，
   貼到下面兩行之間（取代範例的 3 筆）即可。欄位：id、word、pos、definition、example、translation */
